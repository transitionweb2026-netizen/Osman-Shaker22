export const messages: Record<AdminLocale, Record<MessageKey, string>> = { en, ar };

export function translate(locale: AdminLocale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = messages[locale][key] ?? messages.en[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

/** "3 minutes ago" style times in the interface language. */
export function relativeTime(locale: AdminLocale, iso: string | null | undefined): string {
  if (!iso) return messages[locale].never;
  const seconds = (Date.now() - new Date(iso).getTime()) / 1000;
  if (seconds < 45) return messages[locale].justNow;
  const format = new Intl.RelativeTimeFormat(locale === "ar" ? "ar-EG" : "en", { numeric: "auto" });
  const units: [Intl.RelativeTimeFormatUnit, number][] = [
    ["minute", 60],
    ["hour", 3600],
    ["day", 86400],
    ["month", 2592000],
    ["year", 31536000],
  ];
  let unit: Intl.RelativeTimeFormatUnit = "minute";
  let size = 60;
  for (const [u, s] of units) if (seconds >= s) [unit, size] = [u, s];
  return format.format(-Math.round(seconds / size), unit);
}

export function formatDateTime(locale: AdminLocale, iso: string | null | undefined): string {
  if (!iso) return "—";
  return new Intl.DateTimeFormat(locale === "ar" ? "ar-EG" : "en-GB", { dateStyle: "medium", timeStyle: "short" }).format(
    new Date(iso),
  );
}
