import type { CSSProperties } from "react";
import { preload } from "react-dom";
import variantsJson from "@/content/media-variants.generated.json";
import type { MediaAsset } from "@/content/types";
import { cx } from "@/lib/cx";
import type { Resolved } from "@/lib/localize";

type Variant = { width: number; height: number; widths: number[]; color: string };

const variants: Record<string, Variant> = variantsJson;

type MediaImageProps = {
  image: Resolved<MediaAsset>;
  /** Rendered width at each breakpoint, as for the `sizes` attribute. */
  sizes: string;
  /** Above-the-fold image: preloaded with high priority instead of lazy-loaded. */
  priority?: boolean;
  /** Treat as decorative (empty alt) when the surrounding content already describes it. */
  decorative?: boolean;
  className?: string;
  style?: CSSProperties;
};

/**
 * Responsive image for the static export.
 *
 * `/media/<name>` sources use the WebP widths generated by `npm run images`
 * (listed in `content/media-variants.generated.json`). Any other `src`
 * (e.g. a Supabase Storage URL) is rendered as-is.
 */
export function MediaImage({ image, sizes, priority = false, decorative = false, className, style }: MediaImageProps) {
  const name = image.src.startsWith("/media/") ? image.src.slice("/media/".length) : null;
  const variant = name ? variants[name] : undefined;

  const alt = decorative ? "" : image.alt;
  const common = {
    className: cx("media-img", className, image.mirrorInRtl && "mirror-rtl"),
    loading: priority ? ("eager" as const) : ("lazy" as const),
    decoding: "async" as const,
    fetchPriority: priority ? ("high" as const) : undefined,
    // Crop focus is applied by the `.media-img` rule in globals.css.
    style: {
      "--pos": image.position,
      "--pos-mobile": image.positionMobile,
      backgroundColor: variant?.color,
      ...style,
    } as CSSProperties,
  };

  if (!variant) {
    // eslint-disable-next-line @next/next/no-img-element -- static export renders plain <img>
    return <img src={image.src} alt={alt} {...common} />;
  }

  const srcSet = variant.widths.map((w) => `/media/${name}-${w}.webp ${w}w`).join(", ");
  const fallbackWidth = variant.widths.find((w) => w >= 960) ?? variant.widths.at(-1);
  const src = `/media/${name}-${fallbackWidth}.webp`;

  if (priority) {
    preload(src, { as: "image", imageSrcSet: srcSet, imageSizes: sizes, fetchPriority: "high" });
  }

  return (
    // eslint-disable-next-line @next/next/no-img-element -- static export renders plain <img>
    <img
      src={src}
      srcSet={srcSet}
      sizes={sizes}
      width={variant.width}
      height={variant.height}
      alt={alt}
      {...common}
    />
  );
}
